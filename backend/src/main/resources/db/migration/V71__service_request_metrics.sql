CREATE TABLE ops.service_request_metrics (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    request_id varchar(64) NOT NULL,
    operation varchar(32) NOT NULL,
    subject_hash char(64) NOT NULL,
    dedup_key char(64) UNIQUE,
    started_at timestamptz NOT NULL,
    duration_ms bigint NOT NULL CHECK (duration_ms >= 0),
    outcome varchar(12) NOT NULL CHECK (outcome IN ('SUCCESS','FAILED','REJECTED')),
    error_code varchar(40),
    response_type varchar(24),
    provider varchar(24),
    model varchar(80),
    input_tokens bigint,
    output_tokens bigint,
    model_rounds integer,
    provider_calls integer,
    provider_retries integer,
    provider_ms bigint,
    provider_errors jsonb,
    provider_last_success timestamptz,
    tool_calls jsonb,
    engine varchar(24),
    engine_calls integer NOT NULL DEFAULT 0 CHECK (engine_calls >= 0),
    engine_ms bigint,
    confidence numeric(5,4),
    needs_review boolean,
    receipt_saved boolean,
    attempts integer NOT NULL DEFAULT 1
);
